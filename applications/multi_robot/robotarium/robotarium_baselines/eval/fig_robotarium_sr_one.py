#!/usr/bin/env python
"""Robotarium arena: success of a single returned plan, one row per map.

Companion to fig_success_budget.py, restricted to the frozen Robotarium setting
(3.2 x 2.0 m arena, r = 0.13, one velocity cap -- hence a single column). SR(one)
is the expected success of one randomly drawn candidate of the 64 each baseline
samples: free.mean() over the collision masks, the same scorer as the tables.
MMD-CBS returns a single trajectory, so its SR is plotted as-is.

Cells come from figures/robotarium_cells.json, regenerated by
repro-side scoring of grid_state_planB_multi.json. Rerun after more cells finish:

    python fig_robotarium_sr_one.py figures/robotarium_cells.json figures/robotarium_sr_one.png

`--compact` draws the main-text version in the style of Figure 4 (fig_success_budget.py compact): one row of
five map panels at the paper's text width, Times (synth_style.py), open markers. `--gpa <file>` adds GlobMP
(records with method/map/N and SR_one or SR), drawn in blue and listed first; without it GlobMP is absent.

    python fig_robotarium_sr_one.py figures/robotarium_cells.json figures/robotarium_sr_one_compact.pdf --compact [--gpa <file>]
"""
import json, sys, os, argparse, numpy as np
import matplotlib; matplotlib.use('Agg'); import matplotlib.pyplot as plt

ap = argparse.ArgumentParser(); ap.add_argument('cells'); ap.add_argument('out')
ap.add_argument('--compact', action='store_true'); ap.add_argument('--gpa'); a = ap.parse_args()
cells = json.load(open(a.cells)); out = a.out
MAPS = [('empty', 'Empty'), ('corridor', 'Conveyor (Corridor)'), ('shelf', 'Drop-Region (Shelf)'),
        ('corridorbay', 'Corridor-Bay'), ('crossroom', 'Cross-Room')]
NS = [3, 6, 9, 12]
# colours and markers as in fig_success_budget.py
STY = {'cd': dict(color='#8c564b', marker='P', label='CD'),
       'mmd_cbs': dict(color='#17becf', marker='<', label='MMD-CBS'),
       'pcd_lb': dict(color='#ff7f0e', marker='v', label='PCD-LB'),
       'pcd_shd': dict(color='#2ca02c', marker='s', label='PCD-SHD'),
       'final_projection': dict(color='#e377c2', marker='D', label='Final Proj.'),
       'direct': dict(color='#d62728', marker='o', label='DiRecT')}
ORDER = ['cd', 'mmd_cbs', 'pcd_lb', 'pcd_shd', 'final_projection', 'direct']
C = {(r['method'], r['map'], r['N']): r.get('SR_one') for r in cells}

if a.compact:
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    from synth_style import TEXTWIDTH, BLUE, INK, GRID
    G = {}
    if a.gpa:
        for r in json.load(open(a.gpa)):
            G[r['map'], r['N']] = r.get('SR_one', r.get('SR'))
    order = [m for m in ORDER if any(C.get((m, mp, n)) is not None for mp, _ in MAPS for n in NS)]
    TITLES = {'empty': 'Empty', 'corridor': 'Conveyor', 'shelf': 'Drop-Region', 'corridorbay': 'Corridor-Bay', 'crossroom': 'Cross-Room'}
    FH = 1.35                                           # figure height (in); legend, titles and axis labels keep fixed inch margins
    fig, axes = plt.subplots(1, len(MAPS), figsize=(TEXTWIDTH, FH), sharex=True, sharey=True)
    fig.subplots_adjust(left=0.07, right=0.995, top=1 - 0.42 / FH, bottom=0.35 / FH, wspace=0.12)
    H = []
    for k, (mp, _) in enumerate(MAPS):
        ax = axes[k]
        for m in order:
            y = np.array([np.nan if C.get((m, mp, n)) is None else C[m, mp, n] for n in NS], float)
            if np.all(np.isnan(y)): continue
            st = STY[m]
            h, = ax.plot(NS, y, color=st['color'], marker=st['marker'], ms=3.1, lw=0.9, mew=0.6,
                         mfc='white' if st['marker'] not in ('x', 'P') else st['color'], label=st['label'])
            if k == 0: H.append(h)
        if G:
            yg = np.array([np.nan if G.get((mp, n)) is None else G[mp, n] for n in NS], float)
            ax.plot(NS, yg, color='white', lw=3.2, zorder=5.5, solid_capstyle='round')   # casing, as in Figure 4
            h, = ax.plot(NS, yg, color=BLUE, marker='o', ms=3.8, lw=1.7, label='GlobMP (Ours)', zorder=6)
            if k == 0: H.insert(0, h)
        ax.set_title(TITLES[mp], fontsize=8, pad=2.5, color=INK)
        ax.set_ylim(-0.05, 1.05); ax.set_yticks([0, 0.5, 1]); ax.set_xticks(NS)
        ax.grid(axis='y', color=GRID, lw=0.5); ax.set_axisbelow(True)
    fig.supxlabel('number of robots', fontsize=8, y=0.015)
    fig.supylabel('single-plan success', fontsize=7, x=0.012, y=(1 - 0.42 / FH + 0.35 / FH) / 2)   # centred on the panels
    fig.legend(H, [h.get_label() for h in H], loc='upper center', bbox_to_anchor=(0.53, 1.0), ncol=len(H), frameon=False,
               fontsize=7, handlelength=1.8, columnspacing=0.9)
    for ext in ('.pdf', '.png'): fig.savefig(out.rsplit('.', 1)[0] + ext, dpi=300)
    print('wrote', out, f'({len(MAPS)} maps, {len(order)} baselines, GlobMP {"included" if G else "absent"})'); raise SystemExit

plt.rcParams.update({'font.size': 12})
order = [m for m in ORDER if any(C.get((m, mp, n)) is not None for mp, _ in MAPS for n in NS)]
fig, axes = plt.subplots(len(MAPS), 1, figsize=(4.7, 2.35 * len(MAPS)), sharey=True)
for ri, (mp, title) in enumerate(MAPS):
    ax = axes[ri]
    for m in order:
        y = [C.get((m, mp, n), None) for n in NS]
        y = [np.nan if v is None else v for v in y]
        if all(np.isnan(y)): continue
        st = STY[m]
        ax.plot(NS, y, color=st['color'], marker=st['marker'], ms=5, lw=1.6, label=st['label'])
    ax.set_xticks(NS); ax.set_ylim(-0.04, 1.04); ax.grid(True, ls=':', alpha=0.5)
    ax.set_title(title, fontsize=13)
    ax.set_ylabel('single-plan success', fontsize=12)
    if ri == len(MAPS) - 1: ax.set_xlabel('number of robots', fontsize=13)
h, l = axes[0].get_legend_handles_labels()
fig.legend(h, l, loc='upper center', ncol=3, frameon=False, fontsize=11, bbox_to_anchor=(0.5, 1.0))
fig.tight_layout(rect=(0, 0, 1, 0.945)); fig.savefig(out, dpi=170)
print('wrote', out, f'({len(MAPS)} maps x 1 cap, {len(order)} baselines)')
